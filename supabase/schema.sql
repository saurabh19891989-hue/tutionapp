drop view if exists public.invoice_summary; -- recreated: its i.* columns change when invoices gains columns
create view public.invoice_summary
with (security_invoker = true) as
select i.*,
       s.full_name as student_name,
       coalesce((select sum(p.amount) from public.payments p
                  where p.invoice_id = i.id and p.status = 'confirmed'), 0) as paid_amount
from public.invoices i
join public.students s on s.id = i.student_id;

create or replace view public.student_balances
with (security_invoker = true) as
select s.id as student_id,
       s.full_name,
       s.active,
       coalesce((select sum(amount) from public.invoices i
                  where i.student_id = s.id and i.status = 'issued'), 0) as billed,
       coalesce((select sum(amount) from public.payments p
                  where p.student_id = s.id and p.status = 'confirmed'), 0) as paid,
       coalesce((select sum(amount) from public.payments p
                  where p.student_id = s.id and p.status = 'pending'), 0) as pending,
       coalesce((select sum(public.class_amount(c.fee, c.is_trial, c.start_at, c.end_at, s.billing_type,
                                                 s.fee_per_class, s.hourly_rate))
                  from public.classes c
                  where c.student_id = s.id and c.status = 'completed' and c.invoice_id is null
                    -- monthly plans: only extra classes that were given their own fee
                    and (s.billing_type <> 'monthly' or (c.fee is not null and not c.is_trial))), 0) as unbilled
from public.students s;

