-- Book one of the teacher's open slots
create or replace function public.book_slot(p_slot uuid, p_student uuid, p_mode text default null, p_note text default null)
returns uuid
language plpgsql security definer set search_path = public
as $$
declare
  v_slot    public.slots;
  v_student public.students;
  v_mode    text;
  v_class   uuid;
  v_notice  int;
begin
  if not (public.is_admin() or p_student in (select public.my_student_ids())) then
    raise exception 'You cannot book for this student';
  end if;

  select * into v_slot from public.slots where id = p_slot for update;
  if not found then raise exception 'Slot not found'; end if;
  if v_slot.class_id is not null then raise exception 'Sorry, this slot was just booked by someone else'; end if;

  select booking_notice_hours into v_notice from public.app_settings where id = 1;
  if v_slot.start_at < now() + make_interval(hours => coalesce(v_notice, 0)) and not public.is_admin() then
    raise exception 'This slot is too soon to book online. Please call the teacher.';
  end if;

  select * into v_student from public.students where id = p_student;
  v_mode := coalesce(nullif(p_mode, ''),
                     case when v_slot.mode = 'either' then v_student.default_mode else v_slot.mode end);
  if v_slot.mode <> 'either' and v_mode <> v_slot.mode then
    raise exception 'This slot is only available for % classes', v_slot.mode;
  end if;

  -- fee stays empty (= worked out from the plan), so changing the class length later changes the fee
  insert into public.classes (student_id, start_at, end_at, mode, status, request_note, meeting_link, requested_by)
  values (p_student, v_slot.start_at, v_slot.end_at, v_mode, 'scheduled', p_note,
          case when v_mode = 'online' then v_student.meeting_link end,
          auth.uid())
  returning id into v_class;

  update public.slots set class_id = v_class where id = p_slot;
  return v_class;
end;
$$;

-- Ask for a class at a custom time (teacher approves)
create or replace function public.request_class(p_student uuid, p_start timestamptz, p_end timestamptz, p_mode text, p_note text default null)
returns uuid
language plpgsql security definer set search_path = public
as $$
declare v_class uuid;
begin
  if not (public.is_admin() or p_student in (select public.my_student_ids())) then
    raise exception 'You cannot request for this student';
  end if;
  if p_start < now() then raise exception 'Please pick a future time'; end if;
  if p_mode not in ('home', 'online') then raise exception 'Invalid mode'; end if;

  insert into public.classes (student_id, start_at, end_at, mode, status, request_note, requested_by)
  values (p_student, p_start, p_end, p_mode, 'requested', p_note, auth.uid())
  returning id into v_class;
  return v_class;
end;
$$;

-- Ask to move a booked class to another time (teacher approves; the old class is then cancelled)
create or replace function public.request_reschedule(p_class uuid, p_start timestamptz, p_end timestamptz, p_note text default null)
returns uuid
language plpgsql security definer set search_path = public
as $$
declare
  v_old public.classes;
  v_new uuid;
begin
  select * into v_old from public.classes where id = p_class;
  if not found then raise exception 'Class not found'; end if;
  if not (public.is_admin() or v_old.student_id in (select public.my_student_ids())) then
    raise exception 'Not allowed';
  end if;
  if v_old.status <> 'scheduled' then raise exception 'Only booked classes can be moved'; end if;
  if p_start < now() then raise exception 'Please pick a future time'; end if;
  if p_end <= p_start then raise exception 'The class must end after it starts'; end if;
  if exists (select 1 from public.classes where replaces_class = p_class and status = 'requested') then
    raise exception 'You already asked to move this class. Wait for the teacher, or withdraw that request first.';
  end if;

  insert into public.classes (student_id, start_at, end_at, mode, status, subject, request_note, meeting_link,
                              is_trial, fee, requested_by, replaces_class)
  values (v_old.student_id, p_start, p_end, v_old.mode, 'requested', v_old.subject, p_note, v_old.meeting_link,
          v_old.is_trial, v_old.fee, auth.uid(), p_class)
  returning id into v_new;
  return v_new;
end;
$$;

-- Cancel an upcoming class (students/parents need enough notice).
-- p_reopen: put a booked slot back on the calendar for others (the teacher may say no, e.g. when ill).
drop function if exists public.cancel_class(uuid, text);
create or replace function public.cancel_class(p_class uuid, p_reason text default null, p_reopen boolean default true)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_class  public.classes;
  v_notice int;
begin
  select * into v_class from public.classes where id = p_class for update;
  if not found then raise exception 'Class not found'; end if;
  if not (public.is_admin() or v_class.student_id in (select public.my_student_ids())) then
    raise exception 'Not allowed';
  end if;
  if v_class.status not in ('requested', 'scheduled') then
    raise exception 'Only upcoming classes can be cancelled';
  end if;
  if not public.is_admin() and v_class.status = 'scheduled' then
    select cancel_notice_hours into v_notice from public.app_settings where id = 1;
    if v_class.start_at < now() + make_interval(hours => coalesce(v_notice, 0)) then
      raise exception 'Too late to cancel online (needs % hours notice). Please call the teacher.', v_notice;
    end if;
  end if;

  update public.classes set status = 'cancelled', cancel_reason = p_reason where id = p_class;
  if p_reopen or not public.is_admin() then
    update public.slots set class_id = null where class_id = p_class;
  else
    delete from public.slots where class_id = p_class;
  end if;
end;
$$;

