create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.app_settings s
    where lower(coalesce(auth.jwt() ->> 'email', '')) in (select lower(e) from unnest(s.admin_emails) e)
  );
$$;

-- What a class costs: trial = free, explicit fee wins, else by billing plan
create or replace function public.class_amount(p_fee numeric, p_trial boolean, p_start timestamptz, p_end timestamptz,
                                               p_billing text, p_per_class numeric, p_hourly numeric)
returns numeric
language sql immutable set search_path = ''
as $$
  select case
    when p_trial then 0
    when p_fee is not null then p_fee
    when p_billing = 'per_hour' then round(extract(epoch from (p_end - p_start)) / 3600.0 * coalesce(p_hourly, 0), 2)
    when p_billing = 'per_class' then coalesce(p_per_class, 0)
    else 0
  end;
$$;

create or replace function public.my_student_ids()
returns setof uuid
language sql stable security definer set search_path = public
as $$
  select student_id from public.student_members where user_id = auth.uid();
$$;

-- Link a login to any student whose student/parent email matches it
create or replace function public.link_user_to_students(p_user uuid, p_email text)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  insert into public.student_members (student_id, user_id, relation)
  select s.id, p_user,
         case when lower(s.student_email) = lower(p_email) then 'student' else 'parent' end
  from public.students s
  where p_email is not null
    and (lower(s.student_email) = lower(p_email) or lower(s.parent_email) = lower(p_email))
  on conflict do nothing;
end;
$$;

-- New sign-up → create profile + auto-link by email
create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  v_type text := coalesce(new.raw_user_meta_data ->> 'account_type', 'parent');
begin
  if exists (select 1 from public.app_settings s
             where lower(new.email) in (select lower(e) from unnest(s.admin_emails) e)) then
    v_type := 'teacher';
  elsif v_type not in ('student', 'parent') then
    v_type := 'parent';
  end if;

  insert into public.profiles (id, email, full_name, phone, account_type)
  values (new.id, new.email,
          nullif(new.raw_user_meta_data ->> 'full_name', ''),
          nullif(new.raw_user_meta_data ->> 'phone', ''),
          v_type)
  on conflict (id) do nothing;

  perform public.link_user_to_students(new.id, new.email);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- New/edited student → link any existing logins with matching email
create or replace function public.handle_student_emails()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  insert into public.student_members (student_id, user_id, relation)
  select new.id, p.id,
         case when lower(p.email) = lower(new.student_email) then 'student' else 'parent' end
  from public.profiles p
  where lower(p.email) = lower(new.student_email) or lower(p.email) = lower(new.parent_email)
  on conflict do nothing;
  return new;
end;
$$;

drop trigger if exists on_student_emails on public.students;
create trigger on_student_emails
  after insert or update of student_email, parent_email on public.students
  for each row execute function public.handle_student_emails();

