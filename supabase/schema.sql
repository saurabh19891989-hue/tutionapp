-- student_members
create policy members_read  on public.student_members for select to authenticated
  using (public.is_admin() or user_id = auth.uid());
create policy members_admin on public.student_members for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- classes (students/parents create via RPCs only)
create policy classes_read  on public.classes for select to authenticated
  using (public.is_admin() or student_id in (select public.my_student_ids()));
create policy classes_admin on public.classes for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- slots: everyone signed in can see open slots
create policy slots_read  on public.slots for select to authenticated using (true);
create policy slots_admin on public.slots for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- invoices
create policy invoices_read  on public.invoices for select to authenticated
  using (public.is_admin() or student_id in (select public.my_student_ids()));
create policy invoices_admin on public.invoices for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- payments: families can submit "I have paid" (pending) for their own student
create policy payments_read   on public.payments for select to authenticated
  using (public.is_admin() or student_id in (select public.my_student_ids()));
create policy payments_submit on public.payments for insert to authenticated
  with check (public.is_admin()
              or (student_id in (select public.my_student_ids()) and status = 'pending' and submitted_by = auth.uid()));
create policy payments_admin  on public.payments for all to authenticated
  using (public.is_admin()) with check (public.is_admin());
-- families can take back their own "I have paid" report while it is still unchecked
create policy payments_withdraw on public.payments for delete to authenticated
  using (status = 'pending' and submitted_by = auth.uid());

-- announcements
create policy notices_read  on public.announcements for select to authenticated using (true);
create policy notices_admin on public.announcements for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- =====================================================================
--  Grants (nothing for anonymous visitors)
-- =====================================================================
grant usage on schema public to authenticated;
revoke all on all tables in schema public from anon;
grant select, insert, update, delete on all tables in schema public to authenticated;
-- profiles: users may only change their name/phone, never email or account type
revoke update on public.profiles from authenticated;
grant update (full_name, phone) on public.profiles to authenticated;
-- app_settings: everyone signed in reads the public columns; the admin list
-- is only readable by admins through get_admin_emails() (updates stay admin-only via RLS)
revoke select on public.app_settings from authenticated;
grant select (id, brand_name, teacher_name, phone, contact_email, upi_id, upi_payee_name,
              default_class_minutes, booking_notice_hours, cancel_notice_hours, updated_at)
  on public.app_settings to authenticated;

revoke execute on all functions in schema public from public, anon;
grant execute on function public.is_admin(), public.my_student_ids(),
  public.class_amount(numeric, boolean, timestamptz, timestamptz, text, numeric, numeric),
  public.book_slot(uuid, uuid, text, text),
  public.request_class(uuid, timestamptz, timestamptz, text, text),
  public.cancel_class(uuid, text, boolean),
  public.request_reschedule(uuid, timestamptz, timestamptz, text),
  public.generate_invoice(uuid, date, date, date),
  public.link_member(uuid, uuid, text),
  public.get_admin_emails()
  to authenticated;
